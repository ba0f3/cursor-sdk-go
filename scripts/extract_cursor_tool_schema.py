#!/usr/bin/env python3
"""Extract the pinned native tool oneof; check mode detects stale policy aliases."""
import argparse
import hashlib
import re
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = args.reference.read_bytes()
    expected = "9abb6817a7e7792e1b3109d08c84cb69b8ab3027e3c6ed7170c60c6b664991ab"
    if hashlib.sha256(data).hexdigest() != expected:
        raise SystemExit("reference does not match the pinned official v1.2.0 bridge")
    descriptor = data.decode("latin1").split('"ToolCall|', 1)[1].split('\n', 1)[0]
    names = re.findall(r"\b([a-z_]+_tool_call) #\d+ tool\b", descriptor)
    if len(names) != 72 or len(set(names)) != len(names):
        raise SystemExit("unexpected pinned native tool oneof")
    text = '''// Code generated by scripts/extract_cursor_tool_schema.py; DO NOT EDIT.
package agentwire

/**
 * @brief Native tool oneof names from the pinned official Cursor SDK v1.2.0 descriptor.
 * @details Binary SHA-256: ''' + expected + '''.
 */
const nativeToolSchema = `
''' + "\n".join(names) + "\n`\n"
    target = Path(__file__).resolve().parents[1] / "bridge/agentwire/tool_schema.go"
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("native tool schema is stale")
    else:
        target.write_text(text)
    print(f"verified {len(names)} native tool variants")


if __name__ == "__main__":
    main()
