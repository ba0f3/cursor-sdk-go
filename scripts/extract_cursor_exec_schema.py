#!/usr/bin/env python3
"""Extract the pinned native exec inventory and its nested result descriptors."""

import argparse
import hashlib
import re
from pathlib import Path


PINNED_SHA256 = "9abb6817a7e7792e1b3109d08c84cb69b8ab3027e3c6ed7170c60c6b664991ab"
PINNED_COMMIT = "67ee5ba64d68f8e94bd9b7656050aaa1cdbc9977"


def extract(data):
    """Resolve compact descriptor references from the immutable official binary."""
    if hashlib.sha256(data).hexdigest() != PINNED_SHA256:
        raise SystemExit("reference does not match the pinned official v1.2.0 bridge")
    source = data.decode("latin1")
    anchor = source.index('"ExecServerMessage|')
    descriptors = {}
    for match in re.finditer(r'return \["([^"\n]+)"([^\n;]*)\];', source):
        descriptor = match[1]
        name = descriptor.split("|", 1)[0]
        references = [value.strip() for value in match[2].lstrip(",").split(",") if value.strip()]
        candidate = (descriptor, references, match.start())
        if name not in descriptors or abs(match.start() - anchor) < abs(descriptors[name][2] - anchor):
            descriptors[name] = candidate

    def fields(name):
        descriptor, references, _ = descriptors[name.replace("_", ".") if name not in descriptors else name]
        return [(int(number), field, references[int(index)]) for number, field, index in
                re.findall(r"\|(\d+) (\w+) #(\d+) message", descriptor)]

    server = fields("ExecServerMessage")
    client = {name: (number, typ) for number, name, typ in fields("ExecClientMessage")}
    if len(server) != 33 or len(client) != 33:
        raise SystemExit("unexpected pinned native exec oneof")
    variants = []
    for number, name, argument_type in server:
        result_name = {"shell_stream_args": "shell_stream", "git_diff_request": "git_diff_response"}.get(
            name, name.removesuffix("_args") + "_result")
        if result_name not in client:
            raise SystemExit(f"missing pinned exec result for {name}")
        result_number, result_type = client[result_name]
        variants.append((number, name, argument_type, result_number, result_type))

    selected = {"ExecServerMessage", "ExecClientMessage"}
    selected.update(descriptors["ExecServerMessage"][1])
    for result_type in descriptors["ExecClientMessage"][1]:
        selected.add(result_type)
        selected.update(descriptors[result_type][1])
    resolved = []
    for name in sorted(selected):
        if name in {"ForceBackgroundShellStatus", "ForceBackgroundSubagentStatus"}:
            continue
        descriptor, references, _ = descriptors[name.replace("_", ".") if name not in descriptors else name]
        resolved.append(re.sub(r"#(\d+)", lambda match: "#" + references[int(match[1])], descriptor))
    for name in ["ForceBackgroundShellStatus", "ForceBackgroundSubagentStatus"]:
        match = re.search(r'"' + name + r'", (\[\[.*?\]\]), 1\)', source)
        if match is None:
            raise SystemExit(f"missing pinned enum {name}")
        resolved.append(name + "|" + match[1])
    return variants, resolved


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    variants, descriptors = extract(args.reference.read_bytes())
    text = '''// Code generated by scripts/extract_cursor_exec_schema.py; DO NOT EDIT.
package agentwire

/**
 * @brief Complete native exec oneof inventory from the pinned official Cursor SDK v1.2.0.
 * @details Binary SHA-256: ''' + PINNED_SHA256 + '''.
 * @details Upstream commit: ''' + PINNED_COMMIT + '''.
 */
var nativeExecVariants = map[int]nativeExecVariant{
'''
    for number, name, argument_type, result_number, result_type in sorted(variants):
        padding = " " * (3 - len(str(number)))
        text += f'\t{number}:{padding}{{"{name}", "{argument_type}", {result_number}, "{result_type}"}},\n'
    text += '''}

/**
 * @brief Resolved request, result and nested result descriptors, including correlation metadata and status enums.
 */
const nativeExecResultSchema = `
''' + "\n".join(descriptors) + "\n`\n"
    target = Path(__file__).resolve().parents[1] / "bridge/agentwire/exec_schema.go"
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("native exec schema is stale")
    else:
        target.write_text(text)
    print(f"verified {len(variants)} native exec variants and {len(descriptors)} resolved descriptors")


if __name__ == "__main__":
    main()
