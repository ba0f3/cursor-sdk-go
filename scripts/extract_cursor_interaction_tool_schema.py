#!/usr/bin/env python3
"""Extract pinned SDK tool metadata descriptors and converter coverage without executing JavaScript."""

import argparse
import bisect
import hashlib
import json
import re
from pathlib import Path


PINNED_SHA256 = "9abb6817a7e7792e1b3109d08c84cb69b8ab3027e3c6ed7170c60c6b664991ab"


def extract(data):
    if hashlib.sha256(data).hexdigest() != PINNED_SHA256:
        raise SystemExit("reference does not match the pinned official v1.2.0 bridge")
    source = data.decode("latin1")
    classes = list(re.finditer(r"\b([A-Za-z_$][\w$]*) = class ([\w$]+) [^\n{]+\{", source))
    offsets = [match.start() for match in classes]
    messages = {}
    aliases = {}
    for match in re.finditer(r'return \["([^"\n]+)"([^\n;]*)\];', source):
        owner = classes[bisect.bisect_right(offsets, match.start()) - 1]
        refs = [value.strip() for value in match[2].lstrip(",").split(",") if value.strip()]
        descriptor = re.sub(r"#(\d+)", lambda item: "#" + refs[int(item[1])], match[1])
        messages[owner[1]] = descriptor
        aliases[owner[2]] = descriptor
    for name, descriptor in aliases.items():
        messages.setdefault(name, descriptor)
    enums = {}
    for match in re.finditer(r'\b([\w$]+) = /\* @__PURE__ \*/ enumType\([^\n]*?, "([^"\n]+)", (\[\[.*?\]\])(?:, ([^\n]*?))?\);', source):
        values = json.loads(match[3])
        if match[4] == "1":
            simple = match[2].split(".")[-1]
            prefix = (simple[0] + re.sub(r"[A-Z]", lambda letter: "_" + letter[0], simple[1:])).upper() + "_"
            values = [(number, prefix + name) for number, name in values]
        enums[match[1]] = values
    start = source.index("function convertProtoToolCallToSdk(")
    converter = source[start:source.index("\nfunction ", start + 1)]
    supported = dict(re.findall(r'case "(\w+)": \{(?:(?!\n    case).)*?type: "(\w+)"', converter, re.S))
    supported["computerUseToolCall"] = "computerUse"
    declared = set(re.findall(r'case "(\w+)":', converter))
    if len(declared) != 72 or len(supported) != 16:
        raise SystemExit("unexpected pinned SDK tool metadata coverage")
    variants = {}
    for number, name, typ in re.findall(r"\|(\d+) (\w+) #([\w$]+) tool", messages["ToolCall"]):
        camel = re.sub(r"_([a-z])", lambda letter: letter[1].upper(), name)
        if camel not in declared:
            raise SystemExit(f"unclassified pinned metadata variant {name}")
        variants[int(number)] = supported.get(camel, "")
    reachable = set()
    pending = ["ToolCall", "ShellOutputDeltaUpdate"]
    while pending:
        name = pending.pop()
        if name in reachable:
            continue
        reachable.add(name)
        if name in messages:
            pending.extend(re.findall(r"#([\w$]+)", messages[name]))
        elif name not in enums and name not in {"Value", "Struct"}:
            raise SystemExit(f"unresolved pinned metadata type {name}")
    return variants, {name: messages[name] for name in sorted(reachable) if name in messages}, {name: enums[name] for name in sorted(reachable) if name in enums}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    variants, messages, enums = extract(args.reference.read_bytes())
    text = '''// Code generated by scripts/extract_cursor_interaction_tool_schema.py; DO NOT EDIT.
package agentwire

/**
 * @brief Pinned Cursor SDK v1.2.0 tool metadata families; empty values are official explicit-null variants.
 * @details Binary SHA-256: ''' + PINNED_SHA256 + '''.
 * @details Upstream commit: 67ee5ba64d68f8e94bd9b7656050aaa1cdbc9977.
 */
var sdkToolMetadataVariants = map[int]string{
'''
    for number, name in sorted(variants.items()):
        text += f'\t{number}:{" " * (3-len(str(number)))}{json.dumps(name)},\n'
    text += '''}

/**
 * @brief Reachable native descriptors keyed by JS symbol identity, preserving distinct same-name protobuf types.
 */
var sdkToolMetadataDescriptors = map[string]string{
'''
    message_key_width = max(len(json.dumps(name)) for name in messages)
    for name, descriptor in messages.items():
        key = json.dumps(name)
        text += f'\t{key}:{" " * (message_key_width-len(key)+1)}{json.dumps(descriptor)},\n'
    text += '''}

/**
 * @brief Protobuf JSON enum names from the same pinned descriptor graph.
 */
var sdkToolMetadataEnums = map[string]map[int32]string{
'''
    enum_key_width = max(len(json.dumps(name)) for name in enums)
    for name, values in enums.items():
        key = json.dumps(name)
        text += f'\t{key}:{" " * (enum_key_width-len(key)+1)}{{' + ", ".join(f"{number}: {json.dumps(value)}" for number, value in values) + "},\n"
    text += "}\n"
    target = Path(__file__).resolve().parents[1] / "bridge/agentwire/interaction_tool_schema.go"
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("native interaction tool schema is stale")
    else:
        target.write_text(text)
    print(f"verified {len(variants)} tool variants, 16 SDK metadata families, {len(messages)} messages and {len(enums)} enums")


if __name__ == "__main__":
    main()
